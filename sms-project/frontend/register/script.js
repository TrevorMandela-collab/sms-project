/* =========================================================
   Public registration page — redeems a single-use invite
   code (generated by an admin) to create a login. The role
   (student, teacher, or parent) comes from the invite code
   itself, not from anything chosen on this page.
========================================================= */

const registerForm = document.getElementById('registerForm');
const errorBanner = document.getElementById('errorBanner');

// If already logged in, there's nothing to register for.
if (SmsAuth.isLoggedIn()) {
  window.location.href = SmsAuth.homeUrlForRole(SmsAuth.getUser()?.role);
}

function showError(message) {
  errorBanner.textContent = message;
  errorBanner.style.display = 'block';
}

function clearError() {
  errorBanner.style.display = 'none';
}

registerForm.addEventListener('submit', async (e) => {
  e.preventDefault();
  clearError();

  const code = document.getElementById('regCode').value.trim();
  const name = document.getElementById('regName').value.trim();
  const email = document.getElementById('regEmail').value.trim();
  const password = document.getElementById('regPassword').value;

  try {
    const user = await SmsAuth.registerWithCode({ code, name, email, password });
    window.location.href = SmsAuth.homeUrlForRole(user.role);
  } catch (err) {
    showError(err.message);
  }
});
