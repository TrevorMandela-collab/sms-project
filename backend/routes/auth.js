const express = require('express');
const bcrypt = require('bcryptjs');
const { v4: uuidv4 } = require('uuid');
const db = require('../utils/db');
const { signToken, requireAuth, requireRole } = require('../middleware/auth');

const router = express.Router();
const COLLECTION = 'users';

// Valid roles for this system
const ROLES = ['admin', 'teacher', 'parent', 'student'];

// Wraps an async handler so a thrown/rejected error becomes a 500
// instead of an unhandled rejection that hangs the request.
function safe(handler) {
  return (req, res) => {
    handler(req, res).catch(err => {
      console.error('[auth] request failed:', err);
      res.status(500).json({ error: 'Something went wrong on the server.' });
    });
  };
}

/**
 * POST /api/auth/register
 * Public for the very first admin account; after that, only an
 * admin can create new accounts (enforced below).
 */
router.post('/register', safe(async (req, res) => {
  const { name, email, password, role, childIds, teacherId } = req.body;

  if (!name || !email || !password || !role) {
    return res.status(400).json({ error: 'name, email, password, and role are required.' });
  }
  if (!ROLES.includes(role)) {
    return res.status(400).json({ error: `role must be one of: ${ROLES.join(', ')}` });
  }

  const users = await db.readAll(COLLECTION);
  const isFirstUser = users.length === 0;

  // After the first (bootstrap) admin account exists, lock registration
  // down to admins only.
  if (!isFirstUser) {
    const header = req.headers.authorization || '';
    const token = header.startsWith('Bearer ') ? header.slice(7) : null;
    if (!token) {
      return res.status(403).json({ error: 'Only an admin can create new accounts. Log in as admin first.' });
    }
    try {
      const jwt = require('jsonwebtoken');
      const { JWT_SECRET } = require('../middleware/auth');
      const payload = jwt.verify(token, JWT_SECRET);
      if (payload.role !== 'admin') {
        return res.status(403).json({ error: 'Only an admin can create new accounts.' });
      }
    } catch {
      return res.status(403).json({ error: 'Only an admin can create new accounts.' });
    }
  }

  if (users.some(u => u.email.toLowerCase() === email.toLowerCase())) {
    return res.status(409).json({ error: 'An account with that email already exists.' });
  }

  const passwordHash = await bcrypt.hash(password, 10);
  const newUser = {
    id: uuidv4(),
    name,
    email,
    passwordHash,
    role,
    childIds: role === 'parent' ? (childIds || []) : [],
    teacherId: role === 'teacher' ? (teacherId || null) : null,
    createdAt: new Date().toISOString(),
  };

  await db.insert(COLLECTION, newUser);

  const token = signToken(newUser);
  const { passwordHash: _, ...safeUser } = newUser;
  res.status(201).json({ user: safeUser, token, isFirstAdmin: isFirstUser });
}));

/**
 * POST /api/auth/register-with-code
 * Public. A student redeems a single-use invite code (generated by an
 * admin against a specific students record) to create their own login,
 * which gets linked to that student record.
 */
router.post('/register-with-code', safe(async (req, res) => {
  const { code, name, email, password } = req.body;
  if (!code || !name || !email || !password) {
    return res.status(400).json({ error: 'code, name, email, and password are required.' });
  }

  const codes = await db.readAll('invite-codes');
  const invite = codes.find(c => c.code.toUpperCase() === String(code).trim().toUpperCase());
  if (!invite) {
    return res.status(404).json({ error: 'Invalid invite code.' });
  }
  if (invite.used) {
    return res.status(410).json({ error: 'This invite code has already been used.' });
  }
  if (invite.expiresAt && new Date(invite.expiresAt) < new Date()) {
    return res.status(410).json({ error: 'This invite code has expired. Ask your school admin for a new one.' });
  }

  const student = await db.findById('students', invite.studentId);
  if (!student) {
    return res.status(404).json({ error: 'The student record for this code no longer exists.' });
  }

  const users = await db.readAll(COLLECTION);
  if (users.some(u => u.email.toLowerCase() === email.toLowerCase())) {
    return res.status(409).json({ error: 'An account with that email already exists.' });
  }

  const passwordHash = await bcrypt.hash(password, 10);
  const newUser = {
    id: uuidv4(),
    name,
    email,
    passwordHash,
    role: 'student',
    studentId: invite.studentId,
    childIds: [],
    createdAt: new Date().toISOString(),
  };
  await db.insert(COLLECTION, newUser);
  await db.update('invite-codes', invite.id, {
    used: true,
    usedAt: new Date().toISOString(),
    usedByUserId: newUser.id,
  });

  const token = signToken(newUser);
  const { passwordHash: _, ...safeUser } = newUser;
  res.status(201).json({ user: safeUser, token });
}));

/**
 * POST /api/auth/login
 */
router.post('/login', safe(async (req, res) => {
  const { email, password } = req.body;
  if (!email || !password) {
    return res.status(400).json({ error: 'email and password are required.' });
  }

  const users = await db.readAll(COLLECTION);
  const user = users.find(u => u.email.toLowerCase() === email.toLowerCase());
  if (!user) {
    return res.status(401).json({ error: 'Invalid email or password.' });
  }

  const matches = await bcrypt.compare(password, user.passwordHash);
  if (!matches) {
    return res.status(401).json({ error: 'Invalid email or password.' });
  }

  const token = signToken(user);
  const { passwordHash: _, ...safeUser } = user;
  res.json({ user: safeUser, token });
}));

/**
 * GET /api/auth/me
 */
router.get('/me', requireAuth, (req, res) => {
  res.json({ user: req.user });
});

/**
 * GET /api/auth/users  (admin only — manage accounts/roles)
 */
router.get('/users', requireAuth, requireRole('admin'), safe(async (req, res) => {
  const users = (await db.readAll(COLLECTION)).map(({ passwordHash, ...safe }) => safe);
  res.json(users);
}));

/**
 * PATCH /api/auth/users/:id/role  (admin only)
 */
router.patch('/users/:id/role', requireAuth, requireRole('admin'), safe(async (req, res) => {
  const { role } = req.body;
  if (!ROLES.includes(role)) {
    return res.status(400).json({ error: `role must be one of: ${ROLES.join(', ')}` });
  }
  const updated = await db.update(COLLECTION, req.params.id, { role });
  if (!updated) return res.status(404).json({ error: 'User not found.' });
  const { passwordHash, ...safe } = updated;
  res.json(safe);
}));

/**
 * PATCH /api/auth/users/:id  (admin only)
 * Edit an account's name/email/linked-record fields, and optionally
 * reset its password. Does NOT change role — use the /role endpoint
 * for that, since a role change also has knock-on effects on which
 * linked-record field applies.
 * body: { name?, email?, password?, childIds?, teacherId?, studentId? }
 */
router.patch('/users/:id', requireAuth, requireRole('admin'), safe(async (req, res) => {
  const { name, email, password, childIds, teacherId, studentId } = req.body;
  const existing = await db.findById(COLLECTION, req.params.id);
  if (!existing) return res.status(404).json({ error: 'User not found.' });

  if (email && email.toLowerCase() !== existing.email.toLowerCase()) {
    const users = await db.readAll(COLLECTION);
    if (users.some(u => u.id !== existing.id && u.email.toLowerCase() === email.toLowerCase())) {
      return res.status(409).json({ error: 'Another account already uses that email.' });
    }
  }

  const updates = {};
  if (name !== undefined) updates.name = name.trim();
  if (email !== undefined) updates.email = email.trim();
  if (existing.role === 'parent' && childIds !== undefined) updates.childIds = childIds;
  if (existing.role === 'teacher' && teacherId !== undefined) updates.teacherId = teacherId || null;
  if (existing.role === 'student' && studentId !== undefined) updates.studentId = studentId || null;
  if (password) {
    if (password.length < 6) {
      return res.status(400).json({ error: 'Password must be at least 6 characters.' });
    }
    updates.passwordHash = await bcrypt.hash(password, 10);
  }

  const updated = await db.update(COLLECTION, req.params.id, updates);
  const { passwordHash: _, ...safeUser } = updated;
  res.json(safeUser);
}));

/**
 * DELETE /api/auth/users/:id  (admin only)
 * Admins can't delete their own account (avoids accidental lockout).
 */
router.delete('/users/:id', requireAuth, requireRole('admin'), safe(async (req, res) => {
  if (req.params.id === req.user.id) {
    return res.status(400).json({ error: "You can't delete your own account while logged in as it." });
  }
  const removed = await db.remove(COLLECTION, req.params.id);
  if (!removed) return res.status(404).json({ error: 'User not found.' });
  res.status(204).end();
}));

module.exports = router;
