router.get('/me', requireAuth, (req, res) => {
  res.json({ user: req.user });
});

/**
 * GET /api/auth/users  (admin only — manage accounts/roles)
 */
router.get('/users', requireAuth, requireRole('admin'), safe(async (req, res) => {
  const users = (await db.readAll(COLLECTION)).map(({ passwordHash, ...safe }) => safe);
  res.json(users);
}));

/**
 * PATCH /api/auth/users/:id/role  (admin only)
 */
router.patch('/users/:id/role', requireAuth, requireRole('admin'), safe(async (req, res) => {
  const { role } = req.body;
  if (!ROLES.includes(role)) {
    return res.status(400).json({ error: `role must be one of: ${ROLES.join(', ')}` });
  }
  const updated = await db.update(COLLECTION, req.params.id, { role });
  if (!updated) return res.status(404).json({ error: 'User not found.' });
  const { passwordHash, ...safe } = updated;
  res.json(safe);
}));

/**
 * PATCH /api/auth/users/:id  (admin only)
 * Edit an account's name/email/linked-record fields. Deliberately does
 * NOT accept a password — an admin should never be able to set or see
 * another account's password. If someone's locked out, they use their
 * own "forgot password" flow (not built yet) rather than an admin reset.
 * Also does not change role — use the /role endpoint for that.
 * body: { name?, email?, childIds?, teacherId?, studentId? }
 */
router.patch('/users/:id', requireAuth, requireRole('admin'), safe(async (req, res) => {
  const { name, email, childIds, teacherId, studentId } = req.body;
  const existing = await db.findById(COLLECTION, req.params.id);
  if (!existing) return res.status(404).json({ error: 'User not found.' });

  if (email && email.toLowerCase() !== existing.email.toLowerCase()) {
    const users = await db.readAll(COLLECTION);
    if (users.some(u => u.id !== existing.id && u.email.toLowerCase() === email.toLowerCase())) {
      return res.status(409).json({ error: 'Another account already uses that email.' });
    }
  }

  const updates = {};
  if (name !== undefined) updates.name = name.trim();
  if (email !== undefined) updates.email = email.trim();
  if (existing.role === 'parent' && childIds !== undefined) updates.childIds = childIds;
  if (existing.role === 'teacher' && teacherId !== undefined) updates.teacherId = teacherId || null;
  if (existing.role === 'student' && studentId !== undefined) updates.studentId = studentId || null;

  const updated = await db.update(COLLECTION, req.params.id, updates);
  const { passwordHash: _, ...safeUser } = updated;
  res.json(safeUser);
}));

/**
 * PATCH /api/auth/users/:id/status  (admin only)
 * Suspend, time-out, or reinstate an account.
 * body: { status: 'active' | 'suspended', suspendedUntil?: ISOString|null }
 * Leaving suspendedUntil unset/null on a suspension means "indefinite,
 * until an admin manually reinstates it."
 */
router.patch('/users/:id/status', requireAuth, requireRole('admin'), safe(async (req, res) => {
  if (req.params.id === req.user.id) {
    return res.status(400).json({ error: "You can't suspend your own account while logged in as it." });
  }
  const { status, suspendedUntil } = req.body;
  if (!['active', 'suspended'].includes(status)) {
    return res.status(400).json({ error: "status must be 'active' or 'suspended'." });
  }
  const updates = {
    status,
    suspendedUntil: status === 'suspended' ? (suspendedUntil || null) : null,
  };
  const updated = await db.update(COLLECTION, req.params.id, updates);
  if (!updated) return res.status(404).json({ error: 'User not found.' });
  const { passwordHash, ...safeUser } = updated;
  res.json(safeUser);
}));

/**
 * DELETE /api/auth/users/:id  (admin only)
 * Admins can't delete their own account (avoids accidental lockout).
 */
router.delete('/users/:id', requireAuth, requireRole('admin'), safe(async (req, res) => {
  if (req.params.id === req.user.id) {
    return res.status(400).json({ error: "You can't delete your own account while logged in as it." });
  }
  const removed = await db.remove(COLLECTION, req.params.id);
  if (!removed) return res.status(404).json({ error: 'User not found.' });
  res.status(204).end();
}));

module.exports = router;
